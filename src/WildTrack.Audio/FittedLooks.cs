namespace WildTrack.Audio;

/// <summary>
/// A color look described by a small luma/chroma model instead of a hand-written formula, so it can reproduce
/// a reference look closely (the tables were fitted by least squares against a reference, measured on real
/// guitar-video frames; no reference data is shipped). Works in display-referred sRGB, like the app's 3D LUT:
/// <list type="bullet">
/// <item><description><c>Y' = T(Y) + L(hue)·|C|</c>: tone curve plus per-hue brightness (e.g. greens darker).</description></item>
/// <item><description><c>C' = rotate(C, R(hue))·G(hue)·GY(Y) + (TB, TR)(Y')</c>: per-hue saturation and hue shift,
/// saturation by brightness, and split toning.</description></item>
/// <item><description>Per-channel output curves <c>CR, CG, CB</c>.</description></item>
/// </list>
/// Curves over Y have <see cref="YKnots"/> evenly spaced knots on 0..1; curves over hue have <see cref="HueKnots"/>
/// knots around the BT.709 (Cb, Cr) circle starting at +Cb. Everything is linearly interpolated.
/// </summary>
public sealed record FittedLook(
    double[] T, double[] TB, double[] TR,
    double[] L, double[] G, double[] R, double[] GY,
    double[] CR, double[] CG, double[] CB)
{
    public const int YKnots = 9;
    public const int HueKnots = 24;

    // BT.709 luma weights, the same as VideoColorProcessor.Luma.
    const double KR = 0.2126, KB = 0.0722, KG = 1.0 - KR - KB;

    static double AlongY(double[] k, double y)
    {
        double x = Math.Clamp(y, 0, 1) * (k.Length - 1);
        int i = Math.Min((int)x, k.Length - 2);
        double f = x - i;
        return k[i] + (k[i + 1] - k[i]) * f;
    }

    static double AlongHue(double[] k, double hue)
    {
        int n = k.Length;
        double x = (hue < 0 ? hue + 2 * Math.PI : hue) / (2 * Math.PI) * n;
        int i = (int)Math.Floor(x);
        double f = x - i;
        i %= n;
        return k[i] + (k[(i + 1) % n] - k[i]) * f;
    }

    public (double R, double G, double B) Apply(double r, double g, double b)
    {
        double y = KR * r + KG * g + KB * b;
        double cb = (b - y) / (2 * (1 - KB));
        double cr = (r - y) / (2 * (1 - KR));
        double c = Math.Sqrt(cb * cb + cr * cr);
        double h = Math.Atan2(cr, cb);

        double y2 = AlongY(T, y) + AlongHue(L, h) * c;
        double a = AlongHue(R, h);
        double gain = AlongHue(G, h) * AlongY(GY, y);
        double ca = Math.Cos(a), sa = Math.Sin(a);
        double cb2 = (cb * ca - cr * sa) * gain + AlongY(TB, y2);
        double cr2 = (cb * sa + cr * ca) * gain + AlongY(TR, y2);

        double ro = y2 + cr2 * 2 * (1 - KR);
        double bo = y2 + cb2 * 2 * (1 - KB);
        double go = (y2 - KR * ro - KB * bo) / KG;
        return (AlongY(CR, ro), AlongY(CG, go), AlongY(CB, bo));
    }
}

