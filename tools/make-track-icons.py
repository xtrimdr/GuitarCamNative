"""Writes src/GuitarCam.App/Controls/TrackIcons.Data.cs from IconOven's stroke icons (MIT, Appic Marketing LLC).

Usage: python tools/make-track-icons.py path/to/iconoven/icons.json
The icons.json comes from the npm package @iconify-json/iconoven
(https://cdn.jsdelivr.net/npm/@iconify-json/iconoven@1.2.1/icons.json). Circles and rects become paths and every path
is written again with explicit separators, so Avalonia's path parser never meets packed arc flags.
"""
import json, re, sys, os

# (category, [icon ids]) in the order the picker shows them
CATALOG = [
    ("strings", "guitar electric-guitar bass-guitar ukulele banjo mandolin sitar violin cello harp guitar-pick amplifier"),
    ("drums", "drum-kit snare-drum drum cymbal drumsticks bongos conga djembe tambourine maracas xylophone drum-machine drum-pads metronome"),
    ("keys", "piano grand-piano piano-keys synthesizer pipe-organ accordion"),
    ("winds", "flute recorder-flute pan-flute clarinet oboe bassoon saxophone trumpet trombone tuba french-horn harmonica bagpipe"),
    ("more", "microphone-stand microphone-usb headphones turntable vinyl-record music-note music sheet-music"),
]

ARGS = {"m": 2, "l": 2, "h": 1, "v": 1, "c": 6, "s": 4, "q": 4, "t": 2, "a": 7, "z": 0}
NUM = re.compile(r"[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?")


def fmt(x):
    s = f"{x:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def clean_path(d):
    """Re-emits SVG path data command by command with spaces between every number."""
    out, i, cmd = [], 0, None
    while i < len(d):
        ch = d[i]
        if ch in " ,\t\n":
            i += 1
            continue
        if ch.isalpha():
            cmd = ch
            i += 1
            if cmd in "zZ":
                out.append(cmd)
                continue
        n = ARGS[cmd.lower()]
        vals = []
        while len(vals) < n:
            while i < len(d) and d[i] in " ,\t\n":
                i += 1
            if cmd.lower() == "a" and len(vals) in (3, 4):  # arc flags: a single 0 or 1, maybe packed
                vals.append(float(d[i]))
                i += 1
                continue
            m = NUM.match(d, i)
            if not m:
                raise ValueError(f"bad path near {d[i:i+20]!r}")
            vals.append(float(m.group()))
            i = m.end()
        out.append(cmd + " ".join(fmt(v) for v in vals))
        # an implicit repeat after M/m is a line
        if cmd == "M": cmd = "L"
        elif cmd == "m": cmd = "l"
    # a path's first moveto is absolute even when written "m"; joined after another shape it would not be
    if out and out[0].startswith("m"): out[0] = "M" + out[0][1:]
    return " ".join(out)


def attr(tag, name, default=None):
    m = re.search(rf'\s{name}="([^"]*)"', tag)
    return m.group(1) if m else default


def shape_path(tag):
    kind = re.match(r"<(\w+)", tag).group(1)
    if kind == "path":
        return clean_path(attr(tag, "d"))
    if kind == "circle":
        cx, cy, r = (float(attr(tag, k)) for k in ("cx", "cy", "r"))
        return f"M{fmt(cx - r)} {fmt(cy)} A{fmt(r)} {fmt(r)} 0 1 0 {fmt(cx + r)} {fmt(cy)} A{fmt(r)} {fmt(r)} 0 1 0 {fmt(cx - r)} {fmt(cy)} Z"
    if kind == "rect":
        x, y = float(attr(tag, "x", "0")), float(attr(tag, "y", "0"))
        w, h = float(attr(tag, "width")), float(attr(tag, "height"))
        rx = float(attr(tag, "rx", attr(tag, "ry", "0")))
        rx = min(rx, w / 2, h / 2)
        if rx <= 0:
            return f"M{fmt(x)} {fmt(y)} H{fmt(x + w)} V{fmt(y + h)} H{fmt(x)} Z"
        r = fmt(rx)
        return (f"M{fmt(x + rx)} {fmt(y)} H{fmt(x + w - rx)} A{r} {r} 0 0 1 {fmt(x + w)} {fmt(y + rx)} V{fmt(y + h - rx)} "
                f"A{r} {r} 0 0 1 {fmt(x + w - rx)} {fmt(y + h)} H{fmt(x + rx)} A{r} {r} 0 0 1 {fmt(x)} {fmt(y + h - rx)} "
                f"V{fmt(y + rx)} A{r} {r} 0 0 1 {fmt(x + rx)} {fmt(y)} Z")
    raise ValueError(kind)


def strokes(body):
    """(stroke width, path data) per stroke width, inheriting the width of the enclosing <g>."""
    groups = {}
    g_width = None
    for tag in re.findall(r"<[^>]+>", body):
        if tag.startswith("</"):
            if tag == "</g>": g_width = None
            continue
        kind = re.match(r"<(\w+)", tag).group(1)
        if kind == "g":
            g_width = attr(tag, "stroke-width", g_width)
            continue
        if attr(tag, "fill") not in (None, "none") or attr(tag, "stroke") not in (None, "currentColor"):
            raise ValueError(f"unexpected paint in {tag}")
        w = float(attr(tag, "stroke-width", g_width or "1.5"))
        groups.setdefault(w, []).append(shape_path(tag))
    return [(w, " ".join(p)) for w, p in sorted(groups.items())]


def main():
    icons = json.load(open(sys.argv[1], encoding="utf8"))["icons"]
    lines = [
        "// <auto-generated> by tools/make-track-icons.py from IconOven's stroke icons (MIT, Appic Marketing LLC,",
        "// see Assets/Icons/IconOven-LICENSE.txt). Run it again instead of editing this file. </auto-generated>",
        "namespace GuitarCam.App.Controls;",
        "",
        "public static partial class TrackIcons",
        "{",
        "    /// <summary>(category, icon id, strokes: width and path data on a 24×24 grid) in picker order.</summary>",
        "    static readonly (string Category, string Id, (double Width, string Data)[] Strokes)[] Data =",
        "    [",
    ]
    for cat, ids in CATALOG:
        for name in ids.split():
            parts = ", ".join(f'({fmt(w)}, "{d}")' for w, d in strokes(icons[name]["body"]))
            lines.append(f'        ("{cat}", "{name}", [{parts}]),')
    lines += ["    ];", "}", ""]
    out = os.path.join(os.path.dirname(__file__), "..", "src", "GuitarCam.App", "Controls", "TrackIcons.Data.cs")
    with open(out, "w", encoding="utf8", newline="\r\n") as f:
        f.write("\n".join(lines))
    print("wrote", os.path.normpath(out))


main()
